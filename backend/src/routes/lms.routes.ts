import { Router, type RequestHandler } from 'express';
import multer from 'multer';
import { z, type ZodTypeAny } from 'zod';
import type { Environment } from '../config/env.js';
import { lmsController } from '../controllers/lms.controller.js';
import { requireAuth,requirePasswordChanged,requireRole } from '../middleware/auth.js';
import { validateBody } from '../middleware/validate.js';
import { asyncHandler } from '../utils/async-handler.js';
import * as schemas from '../schemas/lms.js';
const upload=multer({storage:multer.memoryStorage(),limits:{fileSize:25*1024*1024,files:1,fields:12,fieldSize:100_000}});
export function lmsRouter(env:Environment) {
  const router=Router();router.use(requireAuth(env));
  router.use(requirePasswordChanged);
  type Roles=('admin'|'teacher'|'student')[];
  function route(method:'get'|'post'|'put'|'patch'|'delete',path:string,operation:string,schema?:ZodTypeAny,roles?:Roles,file=false){
    const handlers:RequestHandler[]=[];
    if(roles)handlers.push(requireRole(...roles));
    handlers.push((req,_res,next)=>{try{for(const [key,value]of Object.entries(req.params)){if(key==='id'||key==='studentId')schemas.id.parse(value);}next();}catch(error){next(error);}});
    if(file)handlers.push(upload.single('file'));
    if(schema)handlers.push(validateBody(schema));
    handlers.push(asyncHandler(lmsController(env,operation)));router[method](path,...handlers);
  }
  const staff:Roles=['admin','teacher'],admin:Roles=['admin'],student:Roles=['student'];
  route('get','/me/profile','profile.get');route('patch','/me/profile','profile.patch',schemas.profileSchema);
  route('get','/me/metrics','profile.metrics');
  route('get','/me/dashboard','dashboard.summary');
  route('get','/admin/departments','departments.list',undefined,admin);
  route('post','/admin/departments','departments.create',schemas.departmentSchema,admin);
  route('patch','/admin/departments/:id','departments.patch',schemas.departmentSchema,admin);
  route('get','/admin/users','admin.users.list',undefined,admin);
  route('post','/admin/users','admin.users.create',schemas.userSchema,admin);
  route('patch','/admin/users/:id','admin.users.patch',schemas.userPatch,admin);
  route('post','/admin/users/:id/reset-password','admin.users.reset',schemas.empty,admin);
  route('get','/me/courses','courses.list');route('get','/admin/courses','admin.courses.list',undefined,admin);
  route('post','/admin/courses','admin.courses.create',schemas.courseSchema,admin);
  route('patch','/admin/courses/:id','admin.courses.patch',schemas.courseSchema,admin);
  route('get','/courses/:id/members','course.members');
  route('get','/admin/courses/:id/teachers','course.teacher-list',undefined,admin);
  route('get','/admin/courses/:id/enrollments','course.enrollments',undefined,admin);
  route('put','/admin/courses/:id/teachers','course.teachers',schemas.teachersSchema,admin);
  route('post','/admin/courses/:id/enrollments','course.enroll',schemas.enrollmentSchema,admin);
  route('post','/admin/courses/:id/enrollments/csv','course.csv',schemas.csvSchema,admin);
  route('delete','/admin/courses/:id/enrollments/:studentId','course.unenroll',undefined,admin);
  route('get','/courses/:id/resources','resources.list');
  route('post','/courses/:id/resources','resource.upload',schemas.resourceSchema,staff,true);
  route('get','/resources/:id/download','resource.download');route('delete','/resources/:id','resource.delete',undefined,staff);
  route('get','/courses/:id/assignments','assignments.list');route('post','/courses/:id/assignments','assignments.create',schemas.assignmentSchema,staff);
  route('post','/courses/:id/assignment-attachments','assignment.attachment.upload',schemas.empty,staff,true);
  route('get','/assignments/:id/attachment','assignment.attachment.download');
  route('get','/assignments/:id','assignment.detail');
  route('patch','/assignments/:id','assignments.patch',schemas.assignmentSchema,staff);route('delete','/assignments/:id','assignments.delete',undefined,staff);
  route('post','/assignments/:id/upload','submission.upload',schemas.empty,student,true);
  route('put','/assignments/:id/submission','submission.put',schemas.submissionSchema,student);
  route('get','/assignments/:id/submissions','submissions.list',undefined,staff);
  route('get','/submissions/:id/download','submission.download');route('patch','/submissions/:id/grade','submission.grade',schemas.gradeSchema,staff);
  route('get','/courses/:id/quizzes','quizzes.list');route('post','/courses/:id/quizzes','quizzes.create',schemas.quizSchema,staff);
  route('get','/quizzes/:id','quizzes.detail',undefined,staff);route('patch','/quizzes/:id','quizzes.patch',schemas.quizSchema,staff);
  route('post','/quizzes/:id/attempt','attempt.start',schemas.empty,student);route('get','/quizzes/:id/attempt','attempt.resume',undefined,student);
  route('post','/quizzes/:id/attempt/submit','attempt.submit',schemas.answersSchema,student);route('get','/quizzes/:id/results','quizzes.results',undefined,staff);
  route('get','/announcements','announcements.list');route('post','/announcements','announcements.create',schemas.announcementSchema,staff);
  route('post','/announcements/read','announcements.read',schemas.readSchema);
  route('patch','/announcements/:id','announcements.patch',schemas.announcementSchema,staff);route('delete','/announcements/:id','announcements.delete',undefined,staff);
  route('get','/me/marks','marks.list',undefined,student);route('get','/courses/:id/gradebook','gradebook',undefined,staff);route('get','/courses/:id/gradebook.csv','gradebook.csv',undefined,staff);
  route('get','/courses/:id/messages','messages.list');route('post','/courses/:id/messages','messages.create',schemas.messageSchema,['teacher','student']);route('delete','/messages/:id','messages.delete');
  route('post','/complaints','complaints.create',schemas.complaintSchema,['teacher','student'],true);
  route('get','/complaints/mine','complaints.mine',undefined,['teacher','student']);route('get','/admin/complaints','admin.complaints',undefined,admin);
  route('patch','/admin/complaints/:id','complaints.review',schemas.reviewSchema,admin);route('get','/complaints/:id/download','complaints.download');
  route('get','/notifications','notifications.list');route('post','/notifications/read','notifications.read',z.object({}).strict());
  route('get','/notifications/counts','notifications.counts');
  return router;
}
